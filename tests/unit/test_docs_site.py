"""The documentation site (zensical.toml, docs_site.py, docs-theme/, docs/requirements.txt, .github/workflows/docs.yml).

* zensical.toml: the nav lists every page of docs/ (and the home page docs_site.py generates from README.md), no MkDocs
  hook (Zensical runs none), the theme override of the edit button and otterdog's logo;
* docs_site.py stages the site: the generated pages with the edit URL of their source, every page rendered for
  Python-Markdown, the staged configuration (the explorer's nav, the paths below .docs-site/), problems failing --strict;
* docs/requirements.txt, installed by the docs workflow, is exactly the ``docs`` group of poetry.lock: pinned versions
  and the hashes of every file (``pip install --require-hashes``). After ``poetry lock``, regenerate it:

      .venv/bin/python tests/unit/test_docs_site.py --write
"""

from __future__ import annotations

import importlib
import re
import sys
import tomllib
from collections.abc import Iterator, Mapping, Sequence
from functools import cache
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
ZENSICAL = ROOT / "zensical.toml"
LOCK = ROOT / "poetry.lock"
PYPROJECT = ROOT / "pyproject.toml"
REQUIREMENTS = DOCS / "requirements.txt"
GROUP = "docs"
REGENERATE = ".venv/bin/python tests/unit/test_docs_site.py --write"
DIRECT = ("zensical", "pymdown-extensions")
SITE_URL = "https://heurtematte.github.io/otterdog-e2e/"
# name==version, an optional environment marker, then the sha256 hashes of its files
PINNED_RE = re.compile(r"^[a-z0-9][a-z0-9._-]*==[0-9][^ ;]*( ; [^-]+)?( --hash=sha256:[0-9a-f]{64})+$")
REPO_URL = "https://github.com/heurtematte/otterdog-e2e"


@cache
def project_config() -> dict[str, Any]:
    """The [project] table of zensical.toml."""
    data = tomllib.loads(ZENSICAL.read_text(encoding="utf-8"))["project"]
    assert isinstance(data, dict)
    return data


@cache
def lock() -> dict[str, Any]:
    """poetry.lock."""
    return tomllib.loads(LOCK.read_text(encoding="utf-8"))


def nav_pages(nav: Any) -> Iterator[str]:
    """The pages of a nav (a page, a {title: page} or {section: [entries]} mapping, or a list of entries)."""
    if isinstance(nav, str):
        yield nav
    elif isinstance(nav, list):
        for entry in nav:
            yield from nav_pages(entry)
    elif isinstance(nav, dict):
        for value in nav.values():
            yield from nav_pages(value)


def render_requirements(data: Mapping[str, Any]) -> str:
    """docs/requirements.txt: every package of the docs group of the lock, pinned, with the hashes of its files."""
    lines = [
        "# The packages of the documentation site: the docs group of poetry.lock, pinned with the hashes of every file.",
        f"# Generated by tests/unit/test_docs_site.py, do not edit: after `poetry lock`, run {REGENERATE}",
        "# Installed by .github/workflows/docs.yml with pip install --require-hashes --only-binary=:all:",
    ]
    packages = sorted((p for p in data["package"] if GROUP in p.get("groups", [])), key=lambda p: p["name"])
    for package in packages:
        markers = package.get("markers")
        marker = markers.get(GROUP) if isinstance(markers, dict) else markers
        requirement = f"{package['name']}=={package['version']}" + (f" ; {marker}" if marker else "")
        hashes = [f"--hash={entry['hash']}" for entry in sorted(package["files"], key=lambda entry: entry["hash"])]
        lines.append(" \\\n    ".join([requirement, *hashes]))
    return "\n".join(lines) + "\n"


# --- zensical.toml ----------------------------------------------------------------------------------------------------
def test_nav_lists_every_page() -> None:
    """Every docs/*.md page is in the nav exactly once, with the home page (index.md, generated from README.md) and
    the entry of the scenario explorer (scenarios/index.md, which docs_scenarios.py turns into a generated section)."""
    pages = list(nav_pages(project_config()["nav"]))
    assert len(pages) == len(set(pages)), "a page is listed twice"
    assert set(pages) == {path.name for path in DOCS.glob("*.md")} | {"index.md", "scenarios/index.md"}
    assert not (DOCS / "index.md").exists(), "the home page is generated from README.md by docs_hooks.py"
    assert not (DOCS / "scenarios").exists(), "the scenario explorer is generated by docs_scenarios.py"


def test_site_settings() -> None:
    """Site and repository URLs, the edit links on main, the theme override, otterdog's logo and favicon; nothing
    Zensical ignores or docs_site.py sets (hooks, watch, MkDocs validation, docs_dir, site_dir)."""
    config = project_config()
    assert config["site_url"] == SITE_URL
    assert config["repo_url"] == REPO_URL
    assert config["edit_uri"] == "edit/main/docs/"
    assert config["extra_javascript"] == ["assets/explorer.js"]
    assert config["extra_css"] == ["assets/explorer.css", "assets/theme.css"]
    assert config["theme"]["custom_dir"] == "docs-theme" and config["theme"].get("name", "material") == "material"
    assert (config["theme"]["logo"], config["theme"]["favicon"]) == (
        "assets/images/otterdog-emblem.png",
        "assets/images/favicon-32x32.png",
    )
    assert (DOCS / config["theme"]["logo"]).is_file() and (DOCS / config["theme"]["favicon"]).is_file()
    assert not {"hooks", "watch", "validation", "docs_dir", "site_dir"} & set(config)
    override = (ROOT / "docs-theme" / "partials" / "actions.html").read_text(encoding="utf-8")
    assert "{% set edit_url = page.meta.edit_url or page.edit_url %}" in override


def test_hero_buttons_open_pages_of_the_nav() -> None:
    """The buttons of the home page's hero (docs-theme/main.html) open pages of the nav: a renamed page breaks no
    link that the strict build does not check."""
    hero = (ROOT / "docs-theme" / "main.html").read_text(encoding="utf-8")
    targets = re.findall(r"\{\{ '([^']*)' \| url \}\}", hero)
    pages = {page.removesuffix("index.md").removesuffix(".md") + "/" for page in nav_pages(project_config()["nav"])}
    assert targets and set(targets) <= {page.replace("//", "/") for page in pages}, targets


def test_markdown_extensions() -> None:
    """GitHub-compatible anchors, mermaid fences, no attr_list (it drops a trailing '{...}' of table cells)."""
    extensions = project_config()["markdown_extensions"]
    assert extensions["toc"]["permalink"] is True
    assert extensions["toc"]["slugify"] == {"object": "pymdownx.slugs.slugify", "kwds": {"case": "lower"}}
    pymdownx = extensions["pymdownx"]
    assert pymdownx["superfences"]["custom_fences"] == [
        {"name": "mermaid", "class": "mermaid", "format": "pymdownx.superfences.fence_code_format"}
    ]
    assert "attr_list" not in extensions and "abbr" in extensions
    assert {"tables", "admonition"} <= set(extensions) and {"magiclink", "tilde", "tasklist"} <= set(pymdownx)


# --- dependencies ------------------------------------------------------------------------------------------------------
def test_docs_group_is_optional() -> None:
    """The docs group of pyproject.toml is optional (`poetry install --with docs`) and holds the site's packages."""
    group = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["tool"]["poetry"]["group"][GROUP]
    assert group["optional"] is True
    assert set(group["dependencies"]) == set(DIRECT)


def test_requirements_match_the_lock() -> None:
    """docs/requirements.txt is the docs group of poetry.lock (versions and hashes)."""
    expected = render_requirements(lock())
    assert REQUIREMENTS.read_text(encoding="utf-8") == expected, f"docs/requirements.txt is stale: run {REGENERATE}"
    pinned = {line.split("==")[0] for line in expected.splitlines() if "==" in line}
    assert set(DIRECT) <= pinned


def test_requirements_pin_every_package_with_hashes() -> None:
    """Every requirement is an exact pin followed by sha256 hashes (pip refuses unhashed ones with --require-hashes)."""
    text = re.sub(r" \\\n\s+", " ", REQUIREMENTS.read_text(encoding="utf-8"))  # join the continuation lines
    requirements = [line for line in text.splitlines() if line and not line.startswith("#")]
    assert len(requirements) >= len(DIRECT)
    for requirement in requirements:
        assert PINNED_RE.match(requirement), requirement


# --- docs_site.py ----------------------------------------------------------------------------------------------------
@pytest.fixture(scope="module")
def site_module() -> Iterator[Any]:
    """docs_site.py (it imports docs_hooks and docs_scenarios, its neighbours at the root of the repository)."""
    sys.path.insert(0, str(ROOT))
    try:
        yield importlib.import_module("docs_site")
    finally:
        sys.path.remove(str(ROOT))


def slugify(value: str, separator: str) -> str:
    """The anchors of the site (pymdownx.slugs.slugify(case='lower')), close enough without the docs group."""
    value = re.sub(r"[^\w\s-]", "", value).strip().lower()
    return re.sub(r"\s+", separator, value)


@pytest.fixture(scope="module")
def staged(site_module: Any) -> Any:
    """The staging of this repository (in memory)."""
    return site_module.stage(ROOT, slugify)


def test_stage_generates_the_pages_with_their_sources(staged: Any) -> None:
    """The home page from README.md and the explorer, each with the edit URL of its source; every page of docs/;
    the theme override; no problem."""
    files = {name: content.decode() for name, content in staged.files.items() if not name.endswith((".png", ".svg"))}
    edit = f"{REPO_URL}/edit/main/"
    assert files["docs/index.md"].startswith(f"---\nedit_url: {edit}README.md\n---\n\n")
    assert files["docs/scenarios/index.md"].startswith(f"---\nedit_url: {edit}docs_scenarios.py\nhide:\n")
    page = files["docs/scenarios/offline/rulesets/val-rulesets.md"]
    assert page.startswith(f"---\nedit_url: {edit}scenarios/offline/rulesets/val-rulesets.yaml\n---\n")
    assert {f"docs/{path.relative_to(DOCS).as_posix()}" for path in DOCS.rglob("*") if path.is_file()} <= set(
        staged.files
    )
    assert {"theme/main.html", "theme/partials/actions.html", "theme/partials/tabs.html"} <= set(files)
    assert "edit_url: " not in files["docs/security.md"]
    assert "> [!" not in files["docs/index.md"], "GitHub callouts of README.md become admonitions"
    assert staged.problems == []


def test_the_staged_configuration(staged: Any, site_module: Any) -> None:
    """zensical.toml with the explorer's section in the nav, the staged paths below .docs-site/ and no hook."""
    config = site_module.read_config(staged.files["zensical.toml"].decode())
    assert (config["docs_dir"], config["site_dir"], config["theme"]["custom_dir"]) == ("docs", "site", "theme")
    assert "hooks" not in config and config["markdown_extensions"] == project_config()["markdown_extensions"]
    assert {key: value for key, value in config.items() if key not in ("nav", "theme", "docs_dir", "site_dir")} == {
        key: value for key, value in project_config().items() if key not in ("nav", "theme")
    }
    pages = list(nav_pages(config["nav"]))
    assert len(pages) == len(set(pages)) and "scenarios/offline/rulesets/val-rulesets.md" in pages
    assert {name.removeprefix("docs/") for name in staged.files if name.endswith(".md")} == set(pages)


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ('[project]\nhooks = ["x.py"]\ntheme.custom_dir = "docs-theme"\nnav = []\n', "hooks must not be set"),
        ('[project]\nsite_dir = "out"\ntheme.custom_dir = "docs-theme"\n', "site_dir must not be set"),
        ('[project]\ntheme.name = "material"\n', "theme.custom_dir must be docs-theme"),
        ('site_name = "x"\n', r"expected a \[project\] table"),
        ("[project\n", "zensical.toml: "),
    ],
)
def test_staged_configuration_refusals(site_module: Any, text: str, message: str) -> None:
    """zensical.toml holds a [project] table, leaves the staged settings to docs_site.py and keeps the theme
    override."""
    with pytest.raises(site_module.SiteError, match=message):
        site_module.staged_config(text, [])


def test_abbreviations_of_the_glossary(site_module: Any, staged: Any) -> None:
    """Every row of the abbreviations table of docs/glossary.md is a definition of the extension abbr (plain text),
    appended to every staged page and never written in a source, where GitHub would show it."""
    glossary = (DOCS / "glossary.md").read_text(encoding="utf-8")
    section = glossary.partition("\n## Abbreviations\n")[2]
    rows = [line for line in section.splitlines() if line.startswith("| ") and not line.startswith("| Abbreviation")]
    defined = site_module.abbreviations(glossary)
    assert len(defined) == len(rows) >= 1 and defined[0].startswith("*[SUT]: System under test")
    assert site_module.abbreviations("# Glossary\n") == []
    for name, content in staged.files.items():
        if name.endswith(".md"):
            assert content.decode().rstrip().endswith(defined[-1]), name
    assert not any("*[SUT]:" in path.read_text(encoding="utf-8") for path in DOCS.rglob("*.md"))


def test_edit_url_front_matter(site_module: Any) -> None:
    """Added, or put in an existing front matter."""
    assert site_module.with_edit_url("# Title\n", "u") == "---\nedit_url: u\n---\n\n# Title\n"
    assert site_module.with_edit_url("---\nhide: [toc]\n---\nx", "u") == "---\nedit_url: u\nhide: [toc]\n---\nx"


def test_write_keeps_unchanged_files_and_the_cache(site_module: Any, tmp_path: Path) -> None:
    """Only the files that differ are written, staged files no longer produced are removed, the cache stays."""
    assert sorted(site_module.write(tmp_path, {"docs/a.md": b"a", "docs/b/c.md": b"c", "zensical.toml": b"m"})) == [
        "docs/a.md",
        "docs/b/c.md",
        "zensical.toml",
    ]
    (tmp_path / ".cache").mkdir()
    (tmp_path / ".cache" / "x").write_text("kept")
    assert site_module.write(tmp_path, {"docs/a.md": b"A", "zensical.toml": b"m"}) == ["docs/a.md", "docs/b/c.md"]
    assert not (tmp_path / "docs" / "b").exists() and (tmp_path / ".cache" / "x").read_text() == "kept"


def test_strict_staging_fails_before_writing(site_module: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A link to a file missing from the repository is a problem: --strict stops before anything is staged."""
    render = site_module.docs_hooks.render_page

    def broken(markdown: str, page: str, repo_url: str, root: Path) -> tuple[str, list[str]]:
        """roles.md links a missing file."""
        rendered, missing = render(markdown, page, repo_url, root)
        return rendered, [*missing, "../nowhere.yaml"] if page == "roles.md" else missing

    monkeypatch.setattr(site_module.docs_hooks, "render_page", broken)
    with pytest.raises(SystemExit, match="1 problem"):
        site_module.prepare(ROOT, strict=True, staging=tmp_path, slugify=slugify)
    assert not any(tmp_path.iterdir())


def test_signature_follows_the_watched_files(site_module: Any, tmp_path: Path) -> None:
    """A file added or changed under a watched path changes the signature; caches do not."""
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "a.md").write_text("a")
    before = site_module.signature(tmp_path, ("docs", "README.md"))
    (tmp_path / "docs" / "__pycache__").mkdir()
    (tmp_path / "docs" / "__pycache__" / "x.pyc").write_bytes(b"x")
    assert site_module.signature(tmp_path, ("docs", "README.md")) == before
    (tmp_path / "README.md").write_text("r")
    assert site_module.signature(tmp_path, ("docs", "README.md")) != before


def main(argv: Sequence[str]) -> int:
    """``--write`` regenerates docs/requirements.txt from poetry.lock."""
    if list(argv) != ["--write"]:
        sys.stderr.write(f"usage: {REGENERATE}\n")
        return 2
    REQUIREMENTS.write_text(render_requirements(lock()), encoding="utf-8")
    sys.stdout.write(f"wrote {REQUIREMENTS.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
